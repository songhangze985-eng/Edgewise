const nodeMap = Object.fromEntries(NODES.map((n) => [n.id, n]))

export function getNodeById(id) {
  return nodeMap[id] || null
}

export function filterGraph(viewId) {
  const nodes = NODES.filter((n) => n.views.includes(viewId))
  const nodeIds = new Set(nodes.map((n) => n.id))
  const edges = EDGES.filter((e) => e.views.includes(viewId) && nodeIds.has(e.from) && nodeIds.has(e.to))
  return { nodes, edges }
}
